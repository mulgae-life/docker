# 용도 A: 보험 약관 기반 답변 — 근거 인용 정확도 + 환각 저항
import json, urllib.request
URL="http://127.0.0.1:5015/v1/chat/completions"
YAKGWAN = """[제3관 보험금의 지급]
제12조(보험금의 종류 및 지급사유) 회사는 피보험자가 보험기간 중에 상해의 직접결과로써
  사망한 경우(질병으로 인한 사망은 제외합니다) 보험수익자에게 약정한 보험금을 지급합니다.
제13조(보험금 지급에 관한 세부규정) ① 제12조의 사망에는 다음 각 호를 포함합니다.
  1. 실종선고를 받은 경우: 법원에서 인정한 실종기간이 끝나는 때에 사망한 것으로 봅니다.
  2. 관공서에서 수해, 화재나 그 밖의 재난을 조사하고 사망하였다고 통보하는 경우
제14조(보험금을 지급하지 않는 사유) 회사는 다음 중 어느 하나로 보험금 지급사유가 발생한 때에는
  보험금을 지급하지 않습니다.
  1. 피보험자가 고의로 자신을 해친 경우. 다만, 심신상실 등으로 자유로운 의사결정을 할 수 없는
     상태에서 자신을 해친 경우에는 보험금을 지급합니다.
  2. 보험수익자가 고의로 피보험자를 해친 경우
  3. 계약자가 고의로 피보험자를 해친 경우
제15조(보험금 지급절차) ① 회사는 제12조의 서류를 접수한 때에는 접수증을 드리고,
  그 서류를 접수한 날부터 3영업일 이내에 보험금을 지급합니다.
  ② 지급기일 내에 보험금을 지급하지 않았을 때에는 그 다음 날부터 지급일까지의 기간에 대하여
  보험개발원이 공시하는 보험계약대출이율을 연단위 복리로 계산한 금액을 더하여 지급합니다."""

Q=[("근거 인용","보험금은 서류 접수 후 며칠 안에 지급되나요? 근거 조항 번호를 함께 답하세요."),
   ("예외 판단","피보험자가 스스로 목숨을 끊은 경우 보험금이 나오나요?"),
   ("환각 저항","암 진단을 받으면 진단비가 얼마나 나오나요?"),
   ("복합 추론","보험수익자가 피보험자를 해쳤는데 그 수익자가 심신상실 상태였습니다. 보험금은 지급되나요?")]
for n,q in Q:
    msgs=[{"role":"system","content":"당신은 보험 약관 안내 도우미입니다. 반드시 제공된 약관에 근거해서만 답하고, 약관에 없는 내용은 '약관에 명시되어 있지 않습니다'라고 답하세요."},
          {"role":"user","content":f"[약관]\n{YAKGWAN}\n\n[질문] {q}"}]
    b=json.dumps({"model":"Qwen3.8-27B-FP8","messages":msgs,"max_tokens":450,"temperature":0.2,
                  "chat_template_kwargs":{"enable_thinking":False}}).encode()
    r=json.load(urllib.request.urlopen(urllib.request.Request(URL,b,{"Content-Type":"application/json"}),timeout=240))
    print(f"\n━━━ [{n}] {q}\n{r['choices'][0]['message']['content'].strip()[:600]}")
